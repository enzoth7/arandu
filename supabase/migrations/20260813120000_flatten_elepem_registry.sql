  select
    array_agg(contact.contact_value order by contact.id) filter (where contact.contact_type = 'phone') as phones,
    array_agg(contact.contact_value order by contact.id) filter (where contact.contact_type = 'email') as emails
  from elepem_core.facility_contacts as contact
  where contact.facility_id = facility.id and contact.is_current
) as contacts on true
left join lateral (
  select array_agg(value order by value) as values
  from (
    select contact.contact_value as value
    from elepem_core.facility_contacts as contact
    where contact.facility_id = facility.id and contact.is_current and contact.contact_type = 'website'
    union
    select observation.source_url
