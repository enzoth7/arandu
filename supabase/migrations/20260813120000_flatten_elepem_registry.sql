create or replace function app_private.elepem_external_urls_valid(values_to_check text[])
returns boolean
language sql
immutable
strict
set search_path = pg_catalog
as $$
  select coalesce(bool_and(
    item = ''
    or (
      char_length(item) <= 1000
      and item ~* '^https?://'
      and item !~* '^https?://[^/]*supabase\.co(?:/|$)'
      and item !~* '^https?://(?:[^/]*\.)?google\.[^/]+/maps(?:/|$)'
      and item !~* '^https?://maps\.app\.goo\.gl(?:/|$)'
    )
  ), true)
  from unnest(values_to_check) as item;
$$;

revoke all on function app_private.elepem_external_urls_valid(text[])
  from public, anon, authenticated, service_role;

create or replace function app_private.touch_flat_elepem_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = pg_catalog
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

