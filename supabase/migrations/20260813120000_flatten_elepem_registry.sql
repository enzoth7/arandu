  ),
  constraint elepem_osm_arrays_aligned check (
    cardinality(osm_ids) = cardinality(osm_urls)
  ),
  constraint elepem_other_id_arrays_aligned check (
    cardinality(otros_ids_proveedores) = cardinality(otros_ids)
    and cardinality(otros_ids) = cardinality(otros_ids_urls)
  ),
  constraint elepem_source_arrays_aligned check (
    cardinality(fuentes_referencias) >= 1
    and cardinality(fuentes_referencias) <= 200
    and cardinality(fuentes_referencias) = cardinality(fuentes_urls)
    and cardinality(fuentes_urls) = cardinality(fuentes_tipos)
    and cardinality(fuentes_tipos) = cardinality(fuentes_proveedores)
    and cardinality(fuentes_proveedores) = cardinality(fuentes_fechas)
    and cardinality(fuentes_fechas) = cardinality(fuentes_consultadas_at)
    and cardinality(fuentes_consultadas_at) = cardinality(fuentes_campos_respaldados)
  ),
  constraint elepem_external_urls_check check (
    app_private.elepem_external_urls_valid(sitios_web)
    and app_private.elepem_external_urls_valid(instagram_urls)
    and app_private.elepem_external_urls_valid(facebook_urls)
    and app_private.elepem_external_urls_valid(otras_redes_urls)
    and app_private.elepem_external_urls_valid(osm_urls)
    and app_private.elepem_external_urls_valid(otros_ids_urls)
    and app_private.elepem_external_urls_valid(fuentes_urls)
  ),
  constraint elepem_price_traceability_check check (
    (precio_mensual_uyu is null and precio_fecha is null and precio_fuente_url is null and not precio_es_demo)
    or (
      precio_mensual_uyu is not null
      and precio_fecha is not null
      and (
        precio_es_demo
        or (
          precio_fuente_url ~* '^https?://'
          and precio_fuente_url !~* '^https?://[^/]*supabase\.co(?:/|$)'
        )
      )
    )
  ),
  constraint elepem_msp_traceability_check check (
    (msp_habilitado and msp_fuente_url ~* '^https?://' and msp_fecha is not null)
    or (not msp_habilitado and msp_fuente_url is null and msp_fecha is null)
  ),
  constraint elepem_mides_traceability_check check (
    (mides_certificado and mides_fuente_url ~* '^https?://' and mides_fecha is not null)
    or (not mides_certificado and mides_fuente_url is null and mides_fecha is null)
  ),
  constraint elepem_google_manual_link_check check (
    (google_place_id is null and google_maps_url is null and google_verificado_at is null and google_verificado_por is null)
    or (
      google_place_id is not null
      and google_maps_url is not null
      and google_verificado_at is not null
      and google_verificado_por is not null
    )
  ),
  constraint elepem_image_pair_check check (
    imagen_url is not null or imagen_alt is null
  )
);

